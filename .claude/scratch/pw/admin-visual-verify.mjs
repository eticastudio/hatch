// Visual + contrast verify of the Hatch admin React app across all 7 tabs.
// Captures screenshots, counts console errors, and flags any <button> whose
// visible text has WCAG contrast below 3.0 against its own background.
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';

const WP = process.env.HATCH_WP || 'http://localhost:8810';
const USER = process.env.HATCH_USER || 'admin';
const PASS = process.env.HATCH_PASS || 'hatch-verify-2026';
const OUT = path.resolve('docs/screenshots/admin-verify');
fs.mkdirSync(OUT, { recursive: true });

const tabs = ['Connection', 'Design', 'Content', 'Bridge', 'Performance', 'Security', 'Status'];

function parseColor(css) {
  if (!css) return null;
  const m = css.match(/rgba?\(([^)]+)\)/i);
  if (!m) return null;
  const p = m[1].split(',').map((s) => parseFloat(s.trim()));
  return { r: p[0], g: p[1], b: p[2], a: p.length > 3 ? p[3] : 1 };
}
function blend(fg, bg) {
  if (!fg || !bg) return fg;
  const a = fg.a;
  return {
    r: fg.r * a + bg.r * (1 - a),
    g: fg.g * a + bg.g * (1 - a),
    b: fg.b * a + bg.b * (1 - a),
    a: 1,
  };
}
function luminance(c) {
  const ch = [c.r, c.g, c.b].map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
}
function contrast(a, b) {
  const la = luminance(a), lb = luminance(b);
  const lighter = Math.max(la, lb), darker = Math.min(la, lb);
  return (lighter + 0.05) / (darker + 0.05);
}

async function audit(page, tabName) {
  const errors = [];
  const consoleErrs = [];
  const listener = (m) => { if (m.type() === 'error') consoleErrs.push(m.text()); };
  page.on('console', listener);

  const clicked = await page.evaluate((name) => {
    const els = Array.from(document.querySelectorAll('button, a, [role="tab"]'));
    const target = els.find((el) => el.textContent && el.textContent.trim() === name);
    if (target) { target.click(); return true; }
    return false;
  }, tabName);
  if (!clicked) {
    page.off('console', listener);
    return { tab: tabName, clicked: false, consoleErrors: consoleErrs.length, lowContrast: [] };
  }
  await page.waitForTimeout(700);
  await page.screenshot({ path: path.join(OUT, `tab-${tabName.toLowerCase()}.png`), fullPage: true });

  // Walk every visible button + link-styled button, measure contrast.
  const findings = await page.evaluate(() => {
    function walkBgUp(el) {
      let cur = el;
      while (cur) {
        const s = getComputedStyle(cur);
        const bg = s.backgroundColor;
        if (bg && bg !== 'rgba(0, 0, 0, 0)' && bg !== 'transparent') return bg;
        cur = cur.parentElement;
      }
      return 'rgb(255,255,255)';
    }
    const nodes = Array.from(document.querySelectorAll('.hatch-react button, .hatch-react a[href], .hatch-react [role="button"]'));
    const rows = [];
    for (const el of nodes) {
      const txt = (el.innerText || el.textContent || '').trim();
      if (!txt) continue;
      const rect = el.getBoundingClientRect();
      if (rect.width < 4 || rect.height < 4) continue;
      const s = getComputedStyle(el);
      let bg = s.backgroundColor;
      if (!bg || bg === 'rgba(0, 0, 0, 0)' || bg === 'transparent') bg = walkBgUp(el.parentElement);
      rows.push({ text: txt.slice(0, 60), color: s.color, bg });
    }
    return rows;
  });

  const low = [];
  for (const r of findings) {
    const fg = parseColor(r.color);
    const bg = parseColor(r.bg);
    if (!fg || !bg) continue;
    const composed = fg.a < 1 ? blend(fg, bg) : fg;
    const ratio = contrast(composed, bg);
    if (ratio < 3.0) {
      low.push({ text: r.text, ratio: +ratio.toFixed(2), fg: r.color, bg: r.bg });
    }
  }

  page.off('console', listener);
  return { tab: tabName, clicked: true, consoleErrors: consoleErrs.length, lowContrast: low };
}

(async () => {
  const results = [];
  const browser = await chromium.launch({ headless: true });
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();

  // Auth via pre-minted logged_in cookie (login form is blocked in this env).
  // Cookie value comes from HATCH_COOKIE=<name>|<value>, generated by wp-cli:
  //   wp eval 'echo LOGGED_IN_COOKIE . "|" . wp_generate_auth_cookie($uid, time()+86400, "logged_in");'
  const cookieRaw = process.env.HATCH_COOKIE || '';
  if (cookieRaw && cookieRaw.includes('|')) {
    const [name, value] = cookieRaw.split('|');
    await ctx.addCookies([{ name, value, url: WP, httpOnly: true, sameSite: 'Lax' }]);
  } else {
    await page.goto(`${WP}/wp-login.php`);
    await page.fill('#user_login', USER);
    await page.fill('#user_pass', PASS);
    await Promise.all([
      page.waitForNavigation({ waitUntil: 'networkidle' }),
      page.click('#wp-submit'),
    ]);
  }

  await page.goto(`${WP}/wp-admin/admin.php?page=hatch`, { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(1500);

  for (const t of tabs) {
    const r = await audit(page, t);
    results.push(r);
    console.log(`[${t}] clicked=${r.clicked} consoleErrs=${r.consoleErrors} lowContrast=${r.lowContrast.length}`);
    for (const lc of r.lowContrast) {
      console.log(`  LOW ${lc.ratio}x  "${lc.text}"  fg=${lc.fg}  bg=${lc.bg}`);
    }
  }

  fs.writeFileSync(path.join(OUT, '_report.json'), JSON.stringify(results, null, 2));
  await browser.close();
  const totalErr = results.reduce((a, r) => a + r.consoleErrors, 0);
  const totalLow = results.reduce((a, r) => a + r.lowContrast.length, 0);
  console.log(`\nSUMMARY: consoleErrors=${totalErr} lowContrastButtons=${totalLow}`);
})().catch((e) => { console.error('FATAL', e); process.exit(1); });
